echo "      {\"what\": \"Waiting for approval\", \"blocked_by\": \"Legal\", \"since\": \"Nov 1\"}"
echo "    ]"
echo "  }'"
echo ""

# Example 5: Add a milestone
echo "5. Add a milestone to a project"
echo "-------------------------------"
echo "PATCH /api/projects/<project_id>"
echo ""
echo "curl -X PATCH \"${API_URL}/api/projects/p-example-project\" \\"
