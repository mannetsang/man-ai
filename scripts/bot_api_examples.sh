echo ""

# Example 1: List all projects
echo "1. List all projects"
echo "--------------------"
echo "GET /api/projects"
echo ""
echo "curl -X GET \"${API_URL}/api/projects\" \\"
echo "  -H \"Authorization: Bearer \${API_KEY}\""
echo ""

# Example 2: Get a specific project
