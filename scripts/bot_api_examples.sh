#!/bin/bash
# Bot API Usage Examples
#
# These examples show how the bot (Jules) can interact with the Chat Assistant API
# using the bot API key for authentication.

# Configuration
API_URL="${PUBLIC_URL:-https://chat-assistant-onvg62bzra-uc.a.run.app}"
# Replace with actual key from Secret Manager:
